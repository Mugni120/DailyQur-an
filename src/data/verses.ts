// Auto-tag tajwid rules into arabic text for interactive display
export function applyTajwidHighlight(arabText: string): string {
  let result = arabText;

  // Ghunnah Musyaddadah: نّ or مّ
  result = result.replace(/(نّ|مّ)/g, '<span class="tajwid-ghunnah font-bold" title="Ghunnah Musyaddadah (Dengung 2 Harakat)">$1</span>');

  // Iqlab: small meem symbol or nun with mim
  result = result.replace(/([نۢ]|[ـًـٍـٌ]ۢ)/g, '<span class="tajwid-iqlab font-bold" title="Iqlab (Berubah Suara Mim Samar)">$1</span>');

  // Qalqalah: ق ط ب ج د with sukun or waqaf at end
  result = result.replace(/([قطبجد]ْ|[قطبجد]ّ)/g, '<span class="tajwid-qalqalah font-bold" title="Qalqalah (Pantulan Suara)">$1</span>');

  // Idgham Bighunnah markers
  result = result.replace(/(مَّ|نَّ|يَّ|وَّ)/g, '<span class="tajwid-idgham-bighunnah font-bold" title="Idgham Bighunnah (Melebur dengan Dengung)">$1</span>');

  // Idgham Bilaghunnah: لّ or رّ
  result = result.replace(/(لَّ|رَّ)/g, '<span class="tajwid-idgham-bilaghunnah font-bold" title="Idgham Bilaghunnah (Melebur Tanpa Dengung)">$1</span>');

  return result;
}

// Fetch verses for any Surah (cached offline first, then live API if online, with fallback)
export async function getSurahVerses(surahNumber: number): Promise<Ayah[]> {
  if (OFFLINE_VERSES_STORE[surahNumber]) {
    return OFFLINE_VERSES_STORE[surahNumber];
  }

  try {
    const response = await fetch(`https://equran.id/api/v2/surat/${surahNumber}`);
    if (response.ok) {
      const json = await response.json();
      if (json && json.data && json.data.ayat) {
        const fetchedAyahs: Ayah[] = json.data.ayat.map((item: any) => ({
          numberInSurah: item.nomorAyat,
          numberInQuran: item.nomorAyat,
          arab: item.teksArab,
          latin: item.teksLatin,
          translation: item.teksIndonesia,
          juz: 30
        }));
        OFFLINE_VERSES_STORE[surahNumber] = fetchedAyahs;
        return fetchedAyahs;
      }
    }
  } catch (e) {
    // Fallback if offline
  }

  // Graceful generated template for offline demo if API is unreachable
  return [
    {
      numberInSurah: 1,
      numberInQuran: 1,
      arab: "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ",
      latin: "Bismillāhir-raḥmānir-raḥīm(i)",
      translation: "Dengan nama Allah Yang Maha Pengasih lagi Maha Penyayang.",
      juz: 1
    }
  ];
}
